const toSvgDataUri = (svg: string) => {
  const normalizedSvg = svg
    .replace(/<\?xml[\s\S]*?\?>/i, "")
    .replace(/<!DOCTYPE[\s\S]*?>/i, "")
    .trim();
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(normalizedSvg)}`;
};

